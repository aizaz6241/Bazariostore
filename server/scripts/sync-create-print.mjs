// Copies the Create / Print tool into Bazario (admin panel server + team portal).
//   node server/scripts/sync-create-print.mjs "C:\Users\aizaz\Documents\antigravity\eager-hubble"
// After it runs: commit + push → Render and Vercel deploy the new version.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const from = path.resolve(process.argv[2] || 'C:\\Users\\aizaz\\Documents\\antigravity\\eager-hubble');
const OK = /\.(html|js|css)$/i;

const names = fs.readdirSync(from).filter((n) => OK.test(n) && fs.statSync(path.join(from, n)).isFile());
if (!names.includes('index.html')) {
  console.error('index.html not found in', from);
  process.exit(1);
}

// 1) admin panel server (served only to logged-in admins)
const serverDir = path.join(repo, 'server', 'src', 'private-tools', 'create-print');
fs.mkdirSync(serverDir, { recursive: true });
for (const old of fs.readdirSync(serverDir)) if (OK.test(old) && !names.includes(old)) fs.unlinkSync(path.join(serverDir, old));
for (const n of names) fs.copyFileSync(path.join(from, n), path.join(serverDir, n));

// 2) team portal (bundled into its private API route, never a public file)
const files = {};
for (const n of names) files[n] = fs.readFileSync(path.join(from, n), 'utf8');
const out = path.join(repo, 'team-portal', 'lib', 'privateTools', 'createPrintFiles.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  '// GENERATED by server/scripts/sync-create-print.mjs — do not edit by hand.\n' +
    '// The Create / Print tool files, sent only to logged-in portal admins (/api/private-tools/create-print).\n' +
    `const files = ${JSON.stringify(files)};\nexport default files;\n`
);
console.log(`Create / Print synced: ${names.length} files → server + team portal`);
